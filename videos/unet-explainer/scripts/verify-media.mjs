import {execFile} from 'node:child_process';
import {promisify} from 'node:util';
import {readFile,writeFile} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
import assert from 'node:assert/strict';
const root=fileURLToPath(new URL('../',import.meta.url));process.chdir(root);
const project=JSON.parse(await readFile('project.json','utf8'));
const file=`outputs/${project.slug}.mp4`;
const exec=promisify(execFile);const run=(tool,args)=>exec(process.execPath,['scripts/remotion.mjs',tool,...args],{cwd:root,maxBuffer:4*1024*1024});
const probe=async file=>JSON.parse((await run('ffprobe',['-v','error','-show_streams','-show_format','-of','json',file])).stdout);
const media=await probe(file);const video=media.streams.find(s=>s.codec_type==='video');
assert.deepEqual([video.codec_name,video.width,video.height,video.avg_frame_rate,Number(video.nb_frames)],['h264',project.width,project.height,'30/1',project.frames]);
assert.ok(Math.abs(Number(media.format.duration)-project.frames/30)<0.1);
if(['unet-explainer','seaside-skate'].includes(project.slug))assert.ok(media.streams.some(s=>s.codec_type==='audio'&&s.codec_name==='aac'));
const sample=await probe('outputs/checks/isolation-sample.mp4');assert.equal(Number(sample.streams.find(s=>s.codec_type==='video').nb_frames),30);
await run('ffmpeg',['-v','error','-i',file,'-map','0:v:0','-map','0:a?','-c:v','rawvideo','-c:a','pcm_s16le','-f','null','-']);
await run('ffmpeg',['-v','error','-y','-ss',String(project.reviewFrame/30),'-i',file,'-frames:v','1','outputs/checks/final-video-frame.png']);
await writeFile('outputs/checks/media-verification.json',JSON.stringify({file,media,fullDecodePassed:true,sampleFrames:30,rootWorkspaceRuntimeRemoved:true},null,2));
console.log(`PASS ${project.id}: 完整视频 ${project.frames} 帧，参数正确，音视频解码通过，检查片段 30 帧。`);
